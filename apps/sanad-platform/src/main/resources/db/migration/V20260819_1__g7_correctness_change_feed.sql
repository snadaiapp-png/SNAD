-- G7 correctness hardening — separate row version from delta cursor.
-- sync_version remains a row-level optimistic-concurrency token.
-- mobile_change_log.change_id is the monotonic delta cursor.

CREATE TABLE mobile_change_log (
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL REFERENCES tenants(id),
    entity_type VARCHAR(40) NOT NULL CHECK (entity_type IN (
        'account','contact','lead','opportunity','task','note','activity'
    )),
    entity_id UUID NOT NULL,
    entity_version BIGINT NOT NULL,
    change_operation VARCHAR(10) NOT NULL CHECK (change_operation IN ('INSERT','UPDATE','DELETE')),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_mobile_change_log_tenant_entity_cursor
    ON mobile_change_log (tenant_id, entity_type, change_id);
CREATE INDEX idx_mobile_change_log_tenant_record
    ON mobile_change_log (tenant_id, entity_type, entity_id, change_id DESC);

