CREATE OR REPLACE FUNCTION fn_mobile_capture_change()
RETURNS TRIGGER AS $$
DECLARE
    v_tenant UUID;
    v_entity UUID;
    v_version BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_tenant := OLD.tenant_id;
        v_entity := OLD.id;
        v_version := OLD.sync_version;
    ELSE
        v_tenant := NEW.tenant_id;
        v_entity := NEW.id;
        v_version := NEW.sync_version;
    END IF;

    INSERT INTO mobile_change_log
        (tenant_id, entity_type, entity_id, entity_version, change_operation, changed_at)
    VALUES
        (v_tenant, TG_ARGV[0], v_entity, v_version, TG_OP, NOW());

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

