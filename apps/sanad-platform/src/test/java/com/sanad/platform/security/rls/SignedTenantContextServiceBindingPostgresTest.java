package com.sanad.platform.security.rls;

import com.sanad.platform.tenant.domain.Tenant;
import com.sanad.platform.tenant.domain.TenantStatus;
import com.sanad.platform.tenant.repository.TenantRepository;
import com.sanad.platform.user.domain.User;
import com.sanad.platform.user.domain.UserStatus;
import com.sanad.platform.user.repository.UserRepository;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.Map;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * G1 F-INT-01/03/04 — SIGNED tenant-context integration through the REAL
 * application: full Spring context ({@code local} profile, real PostgreSQL
 * chain, RLS-wrapped pool, real repositories, real service-layer beans).
 *
 * <h3>What this test proves (and unit/fixture tests cannot)</h3>
 *
 * <p>It does NOT create any signed context manually for tenant-data access.
 * Every tenant-scoped statement runs inside its own real transaction, and the
 * binding is generated by the APPLICATION itself through one of the two
 * production binding paths:</p>
 *
 * <ol>
 *   <li><b>HTTP-path simulation (request thread)</b> — an authenticated
 *       principal shaped exactly as the JWT filter produces it
 *       ({@code Authentication.details["tenant_id"]}) is placed in the
 *       security context; the first tenant-data statement inside the
 *       transaction triggers {@link TenantRlsConnectionHandler} on the
 *       wrapped pool, which executes slot → HMAC mint →
 *       {@code app_bind_tenant_ctx} with the configured signing key. The
 *       repository write then flows through the enforced policies.</li>
 *   <li><b>Background-path simulation (no principal)</b> — a scheduled-worker
 *       style flow with NO security context uses the real
 *       {@link TenantRlsTransactionContext} bean inside a
 *       {@link TransactionTemplate} transaction; the protocol runs through
 *       the same wrapped pool.</li>
 * </ol>
 *
 * <p>Each transaction mirrors one request/worker unit of work: the binding is
 * established inside the transaction and the assertions run within the same
 * unit — cross-transaction visibility flips exactly as RLS requires.</p>
 *
 * <p>The database side closes the loop: {@code app.ctx_mac} is non-empty (only
 * the SECURITY DEFINER verifier sets it, and only when the mac validates
 * against the caller's own txid/pid), and {@code app_tenant_ctx_text()} — the
 * expression the enforced policies consume — returns the bound tenant. A raw
 * forged GUC without a mac is rejected end-to-end (validator NULL, zero rows).
 * Cross-tenant isolation is asserted in both binding paths.</p>
 */
@SpringBootTest
@ActiveProfiles("local")
@DisplayName("Signed tenant context — application-generated binding through real services")
class SignedTenantContextServiceBindingPostgresTest {

    @Autowired TenantRepository tenants;
    @Autowired UserRepository users;
    @Autowired JdbcTemplate jdbc;
    @Autowired TenantRlsTransactionContext scope;
    @Autowired TransactionTemplate transactionTemplate;

    @AfterEach
    void clearSecurityContext() {
        SecurityContextHolder.clearContext();
    }

    /** Infrastructure seeding (registry rows, not tenant data) — explicitly classified. */
    private Tenant seedTenant(String label) {
        return TenantRlsPreAuthScope.call(() ->
                tenants.saveAndFlush(new Tenant("G1 Signed " + label,
                        "g1-signed-" + label + "-" + UUID.randomUUID(), TenantStatus.ACTIVE)));
    }

    /** Shapes the security context exactly as JwtAuthenticationFilter does after JWT validation. */
    private static void actAsTenant(UUID tenantId) {
        Map<String, Object> details = Map.of(
                "tenant_id", tenantId.toString(),
                "user_id", UUID.randomUUID().toString());
        UsernamePasswordAuthenticationToken auth = UsernamePasswordAuthenticationToken.authenticated(
                "signed-ctx-it", "n/a", java.util.List.of());
        auth.setDetails(details);
        SecurityContextHolder.getContext().setAuthentication(auth);
    }

    @Test
    @DisplayName("handler path: the application binds the signed context from the authenticated principal")
    void handlerPathApplicationGeneratesValidSignedBinding() {
        Tenant a = seedTenant("a");
        Tenant b = seedTenant("b");

        // ── Request 1: the actor authenticates as tenant A and saves a user. ──
        // NO manual context creation — the wrapped pool's handler must bind.
        UUID userIdA = transactionTemplate.execute(status -> {
            actAsTenant(a.getId());
            User saved = users.saveAndFlush(new User(a.getId(),
                    "g1-signed-a-" + UUID.randomUUID() + "@example.test",
                    "G1 Signed User A", UserStatus.ACTIVE));

            // Application-generated binding evidence: the SECURITY DEFINER
            // verifier recorded a mac (only a validating mac reaches that
            // code path) and the HMAC-validated value equals the principal's
            // tenant.
            String boundMac = jdbc.queryForObject(
                    "SELECT current_setting('app.ctx_mac', true)", String.class);
            assertThat(boundMac)
                    .as("the application-generated signed bind must record app.ctx_mac")
                    .isNotBlank();
            String validated = jdbc.queryForObject(
                    "SELECT public.app_tenant_ctx_text()", String.class);
            assertThat(validated)
                    .as("the HMAC validator must confirm the application-bound tenant")
                    .isEqualTo(a.getId().toString());
            return saved.getId();
        });

        // ── Request 2: the actor authenticates as tenant B and saves a user. ──
        UUID userIdB = transactionTemplate.execute(status -> {
            actAsTenant(b.getId());
            User saved = users.saveAndFlush(new User(b.getId(),
                    "g1-signed-b-" + UUID.randomUUID() + "@example.test",
                    "G1 Signed User B", UserStatus.ACTIVE));
            return saved.getId();
        });

        // ── Request 3: under A's binding, B's row is invisible. ──
        transactionTemplate.execute(status -> {
            actAsTenant(a.getId());
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdA))
                    .isEqualTo(1L);
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdB))
                    .as("tenant B's row must be invisible under A's application-generated binding")
                    .isZero();
            return null;
        });

        // ── Request 4: under B's binding, A's row is invisible. ──
        transactionTemplate.execute(status -> {
            actAsTenant(b.getId());
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdB))
                    .as("under B's application-generated binding B's row is visible")
                    .isEqualTo(1L);
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdA))
                    .isZero();
            return null;
        });

        // ── Request 5: the forged raw GUC (no mac) never satisfies the
        // validator — the RT-01 fail-closed contract, end-to-end. The probe
        // simulates a HOSTILE runtime session: no principal, no application
        // binding, only a raw set_config of the tenant GUC. ──
        transactionTemplate.execute(status -> {
            SecurityContextHolder.clearContext();
            TenantRlsPreAuthScope.run(() -> {
                jdbc.execute("SELECT set_config('app.tenant_id', '" + a.getId() + "', true)");
                String forgedValidation = jdbc.queryForObject(
                        "SELECT public.app_tenant_ctx_text()", String.class);
                assertThat(forgedValidation)
                        .as("a forged raw GUC without a mac must NOT satisfy the validator")
                        .isNull();
                assertThat(jdbc.queryForObject("SELECT count(*) FROM public.users", Long.class))
                        .as("a forged raw GUC must expose zero users")
                        .isZero();
            });
            return null;
        });
    }

    @Test
    @DisplayName("background path: no principal — the real TenantRlsTransactionContext bean binds through the wrapped pool")
    void backgroundPathApplicationGeneratesValidSignedBinding() {
        Tenant a = seedTenant("bg-a");
        Tenant b = seedTenant("bg-b");

        // ── Worker unit 1: no principal — the service bean's protocol binds. ──
        UUID userIdA = transactionTemplate.execute(status -> {
            SecurityContextHolder.clearContext();
            scope.applyForCurrentTransaction(a.getId());
            String validated = jdbc.queryForObject(
                    "SELECT public.app_tenant_ctx_text()", String.class);
            assertThat(validated)
                    .as("the real service bean's protocol must produce a validator-confirmed binding")
                    .isEqualTo(a.getId().toString());
            String mac = jdbc.queryForObject(
                    "SELECT current_setting('app.ctx_mac', true)", String.class);
            assertThat(mac).as("the protocol bind must record app.ctx_mac").isNotBlank();
            User saved = users.saveAndFlush(new User(a.getId(),
                    "g1-signed-bg-a-" + UUID.randomUUID() + "@example.test",
                    "G1 Signed BG User A", UserStatus.ACTIVE));
            return saved.getId();
        });

        // ── Worker unit 2: a fresh transaction starts UNBOUND (the binding
        // does not leak across transactions) and re-binds to B. ──
        UUID userIdB = transactionTemplate.execute(status -> {
            // The unbound-precondition read is binding infrastructure — it
            // runs BEFORE any binding exists in this transaction by design.
            String staleTenant = TenantRlsPreAuthScope.call(() ->
                    jdbc.queryForObject(
                            "SELECT current_setting('app.tenant_id', true)", String.class));
            assertThat(staleTenant)
                    .as("a fresh background transaction must start unbound")
                    .isNullOrEmpty();
            scope.applyForCurrentTransaction(b.getId());
            User saved = users.saveAndFlush(new User(b.getId(),
                    "g1-signed-bg-b-" + UUID.randomUUID() + "@example.test",
                    "G1 Signed BG User B", UserStatus.ACTIVE));
            return saved.getId();
        });

        // ── Verification reads run inside signed-bound units. ──
        transactionTemplate.execute(status -> {
            scope.applyForCurrentTransaction(a.getId());
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdA))
                    .isEqualTo(1L);
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdB))
                    .as("background path: cross-tenant row must be invisible")
                    .isZero();
            return null;
        });

        transactionTemplate.execute(status -> {
            scope.applyForCurrentTransaction(b.getId());
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdB))
                    .isEqualTo(1L);
            assertThat(jdbc.queryForObject(
                    "SELECT count(*) FROM public.users WHERE id = ?", Long.class, userIdA))
                    .isZero();
            return null;
        });
    }
}
